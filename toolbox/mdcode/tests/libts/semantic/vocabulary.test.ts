describe('OWL import', () => {
  const TTL = `
    @prefix owl:  <http://www.w3.org/2002/07/owl#> .
    @prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
    @prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .
    @prefix skos: <http://www.w3.org/2004/02/skos/core#> .
    @prefix ex:   <https://example.org/orders#> .

    ex:vocabulary a owl:AnnotationProperty .
    ex:code a owl:AnnotationProperty .
    ex:sortOrder a owl:AnnotationProperty .
    ex:order a owl:AnnotationProperty .
    ex:encodedBy a owl:AnnotationProperty .

    ex:Order a owl:Class ; owl:hasKey ( ex:orderId ) .
    ex:orderId a owl:DatatypeProperty ; rdfs:domain ex:Order ; rdfs:range xsd:string .
    ex:statusKey a owl:DatatypeProperty ; rdfs:domain ex:Order ; rdfs:range xsd:string .
    ex:hasStatus a owl:ObjectProperty ; rdfs:domain ex:Order ;
        rdfs:range ex:OrderStatus ; ex:encodedBy ex:statusKey .

    # A vocabulary by annotation; members are named individuals with a code,
    # a sort order, labels and a definition.
    ex:OrderStatus a owl:Class ; rdfs:label "Order status" ; ex:vocabulary true ;
        owl:hasKey ( ex:statusCode ) .
    ex:statusCode a owl:DatatypeProperty ; rdfs:domain ex:OrderStatus ;
        rdfs:range xsd:string .
    ex:Status_Shipped a owl:NamedIndividual , ex:OrderStatus ; ex:code "SHIPPED" ;
        ex:sortOrder 2 ; rdfs:label "Shipped" ; skos:altLabel "Dispatched" .
    ex:Status_Open a owl:NamedIndividual , ex:OrderStatus ; ex:code "OPEN" ;
        ex:sortOrder 1 ; rdfs:label "Open" ;
        skos:definition "Placed, not yet shipped." .

    # An enumeration: codes from skos:notation, labels from skos:prefLabel.
    ex:Priority a owl:Class ;
        owl:equivalentClass [ a owl:Class ; owl:oneOf ( ex:High ex:Low ) ] .
    ex:High a owl:NamedIndividual ; skos:notation "H" ; skos:prefLabel "High" .
    ex:Low a owl:NamedIndividual ; skos:notation "L" ; skos:prefLabel "Low" .

    # Named instances only: a vocabulary (warned); the code is the local name.
    ex:Channel a owl:Class .
    ex:Web a owl:NamedIndividual , ex:Channel .
    ex:Store a owl:NamedIndividual , ex:Channel ; ex:order 1 .

    # \`vocabulary false\` keeps a class with named instances a data class.
    ex:Region a owl:Class ; ex:vocabulary false .
    ex:North a owl:NamedIndividual , ex:Region .
  `;
  const NS = 'https://example.org/orders#';

  test('the parser reads individuals, codes, orders and the annotation', () => {
    const owl = parseOwl(TTL);
    const ind = (n: string) => owl.individuals!.find(i => i.localName === n)!;
    expect(ind('Status_Open'))
        .toMatchObject(
            {code: 'OPEN', order: '1', label: 'Open', named: true});
    expect(ind('Status_Shipped').synonyms).toEqual(['Dispatched']);
    expect(ind('High')).toMatchObject({code: 'H', label: 'High'});
    expect(ind('Store').order).toBe('1');
    const cls = (n: string) => owl.classes.find(c => c.localName === n)!;
    expect(cls('OrderStatus').vocabulary).toBe(true);
    expect(cls('Region').vocabulary).toBe(false);
    expect(cls('Priority').oneOf).toEqual([`${NS}High`, `${NS}Low`]);
  });

  const r = convertOwlToOsi(TTL, 'orders');
  const m = loadModels(r.yaml, {bindingOptional: true}).models[0];
  const entity = (n: string) => m.entities.find(e => e.name === n)!;

  test('vocabulary classes import their members, sorted by order', () => {
    expect(entity('OrderStatus').members).toEqual([
      {
        code: 'OPEN',
        label: 'Open',
        definition: 'Placed, not yet shipped.',
        order: 1,
        iri: `${NS}Status_Open`,
      },
      {
        code: 'SHIPPED',
        label: 'Shipped',
        synonyms: ['Dispatched'],
        order: 2,
        iri: `${NS}Status_Shipped`,
      },
    ]);
    expect(entity('Priority').members).toEqual([
      {code: 'H', label: 'High', iri: `${NS}High`},
      {code: 'L', label: 'Low', iri: `${NS}Low`},
    ]);
    expect(entity('Channel').members).toEqual([
      {code: 'Store', order: 1, iri: `${NS}Store`},
      {code: 'Web', iri: `${NS}Web`},
    ]);
    expect(entity('Region').members).toBeUndefined();
    expect(r.stats.vocabularies).toBe(3);
  });

  test('a class made a vocabulary only by its instances is warned', () => {
    expect(r.warnings).toContain(
        `class 'Channel' has owl:NamedIndividual instances, so it is imported ` +
        `as a vocabulary of 2 member(s); annotate it \`vocabulary false\` to ` +
        `keep it a data class.`);
    expect(r.warnings.some(w => w.includes(`'OrderStatus'`))).toBe(false);
  });

  test('encodedBy joins the code field to the vocabulary key', () => {
    const rel = m.relationships.find(x => x.name === 'hasStatus')!;
    expect(rel.source.columns).toEqual(['statusKey']);
    expect(rel.destination.columns).toEqual(['statusCode']);
  });

  // The view must hold exactly the rows a hand-maintained generator renders
  // from the same individuals: code, rdfs:label (else the local name), the
  // integer sort order (else NULL), skos:definition (else NULL), the IRI --
  // so such a script can be retired.
  test('the generated view equals the individuals, row for row', () => {
    const bound: SemanticModel = {
      ...m,
      entities: m.entities.map(
          e => e.name === 'Order' ?
              {
                ...e,
                dataSource: 'p.d.orders',
                fields: e.fields.map(f => ({...f, expression: f.name})),
              } :
              e),
    };
    const {views} = lowerVocabularies(bound, GEN_OPTS, []);
    const view = views.find(v => v.name === 'vocab_order_status')!;
    expect(view.ref).toBe('p.d.vocab_order_status');
    expect(view.ddl.split('\n').filter(l => l.startsWith('  STRUCT(')))
        .toEqual([
          "  STRUCT('OPEN' AS code, 'Open' AS label, 1 AS sort_order, " +
              "'Placed, not yet shipped.' AS definition, " +
              `'${NS}Status_Open' AS iri),`,
          "  STRUCT('SHIPPED' AS code, 'Shipped' AS label, 2 AS sort_order, " +
              'CAST(NULL AS STRING) AS definition, ' +
              `'${NS}Status_Shipped' AS iri)`,
        ]);
    // An unlabeled member shows its local name.
    const channel = views.find(v => v.name === 'vocab_channel')!.ddl;
    expect(channel).toContain(`STRUCT('Web' AS code, 'Web' AS label`);
  });
});
