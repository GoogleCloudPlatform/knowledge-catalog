function orderStatus(): Entity {
  return {
    name: 'OrderStatus',
    dataSource: '',
    keys: ['statusCode'],
    description: 'Where an order is in its lifecycle.',
    fields: [
      {name: 'statusCode', type: 'String'},
      {name: 'label', type: 'String'},
      {name: 'sortOrder', type: 'Integer'},
    ],
    members: [
      {
        code: 'OPEN',
        label: 'Open',
        order: 1,
        definition: 'Placed, not yet shipped.',
        iri: 'https://example.org/orders#Open',
      },
      {code: 'SHIPPED', label: 'Shipped', order: 2, synonyms: ['Dispatched']},
      {code: 'ON_HOLD', label: `Customer's hold`, order: 3},
      {code: 'VOID'},
    ],
  };
}

function model(): SemanticModel {
  return {
    name: 'orders',
    entities: [
      {
        name: 'Order',
        dataSource: 'p.d.orders',
        keys: ['orderId'],
        fields: [
          {name: 'orderId', type: 'String', expression: 'order_id'},
          {name: 'statusKey', type: 'String', expression: 'status_key'},
        ],
      },
      orderStatus(),
    ],
    relationships: [{
      name: 'hasStatus',
      source: {entity: 'Order', columns: ['statusKey']},
      destination: {entity: 'OrderStatus', columns: ['statusCode']},
    }],
    metrics: [],
    customExtensions: [{
      vendorName: 'GOOGLE',
      data: JSON.stringify({deploymentTargets: [TARGET]}),
    }],
  };
}

const flat = (s: string) => s.replace(/\s+/g, ' ');

const VOCAB_VIEW = [
  'CREATE OR REPLACE VIEW `p.d.vocab_order_status`',
  "OPTIONS (description = 'Vocabulary OrderStatus: one row per member " +
      "declared in the semantic model. Generated by kcmd; do not edit.') AS",
  'SELECT * FROM UNNEST([',
  "  STRUCT('OPEN' AS code, 'Open' AS label, 1 AS sort_order, " +
      "'Placed, not yet shipped.' AS definition, " +
      "'https://example.org/orders#Open' AS iri),",
  "  STRUCT('SHIPPED' AS code, 'Shipped' AS label, 2 AS sort_order, " +
      'CAST(NULL AS STRING) AS definition, CAST(NULL AS STRING) AS iri),',
  "  STRUCT('ON_HOLD' AS code, 'Customer\\'s hold' AS label, 3 AS sort_order, " +
      'CAST(NULL AS STRING) AS definition, CAST(NULL AS STRING) AS iri),',
  "  STRUCT('VOID' AS code, 'VOID' AS label, CAST(NULL AS INT64) AS " +
      'sort_order, CAST(NULL AS STRING) AS definition, CAST(NULL AS STRING) ' +
      'AS iri)',
  '])',
].join('\n');

const EDGE_VIEW = [
  'CREATE OR REPLACE VIEW `p.d.edge_has_status`',
  "OPTIONS (description = 'Edge hasStatus (Order -> OrderStatus): each Order " +
      'row paired with the OrderStatus member whose code matches its ' +
      "statusKey case-insensitively. Generated by kcmd; do not edit.') AS",
  'SELECT s.order_id AS source_order_id, v.code AS target_code',
  'FROM `p.d.orders` AS s',
  'JOIN `p.d.vocab_order_status` AS v',
  '  ON LOWER(s.status_key) = LOWER(v.code)',
].join('\n');

describe('loader', () => {
  const doc = (status: any, version = '0.2.0.dev0/google') => ({
    version,
    semantic_model: [{
      name: 'orders',
      datasets: [
        {
          name: 'Order',
          source: 'p.d.orders',
          primary_key: ['orderId'],
          fields: [
            {name: 'orderId', expression: 'order_id'},
            {name: 'statusKey', expression: 'status_key'},
          ],
        },
        {name: 'OrderStatus', ...status},
      ],
    }],
  });
  const members = [
    {
      code: 'OPEN',
      label: 'Open',
      order: 1,
      synonyms: ['Placed'],
      definition: 'Not yet shipped.',
      iri: 'https://example.org/orders#Open',
    },
    {code: 'VOID'},
  ];

  test('members load onto the IR; a vocabulary needs no source or key', () => {
    const {models, warnings} = fromDocument(doc({members}));
    const e = models[0].entities.find(x => x.name === 'OrderStatus')!;
    expect(e.members).toEqual(members);
    expect(e.dataSource).toBe('');
    expect(warnings.filter(w => w.includes('OrderStatus'))).toEqual([]);
  });

  test('members are a native extension: vanilla Ossie rejects them', () => {
    expect(() => fromDocument(doc(
               {
                 source: 'p.d.order_status',
                 primary_key: ['code'],
                 fields: [{name: 'code', expression: 'code'}],
                 members,
               },
               '0.2.0.dev0')))
        .toThrow();
  });

  test('codes differing only in case are a load error', () => {
    expect(() => fromDocument(doc({members: [{code: 'open'}, {code: 'OPEN'}]})))
        .toThrow(/member code 'OPEN' repeats 'open'/);
  });

  test('an abstract or defined vocabulary is a load error', () => {
    expect(() => fromDocument(doc({abstract: true, members}))).toThrow(/abstract/);
  });

  test('a member needs a non-empty code', () => {
    expect(() => fromDocument(doc({members: [{label: 'Open'}]}))).toThrow();
    expect(() => fromDocument(doc({members: [{code: ''}]}))).toThrow();
  });
});

describe('default bindings', () => {
  test('a generated vocabulary binds its key to code, fields by name', () => {
    const e = withVocabularyBindings(orderStatus());
    expect(e.fields.map(f => [f.name, f.expression])).toEqual([
      ['statusCode', 'code'],
      ['label', 'label'],
      ['sortOrder', 'sort_order'],
    ]);
    expect(e.keys).toEqual(['statusCode']);
  });

  test('a keyless vocabulary is keyed by its code', () => {
    const bare = withVocabularyBindings(
        {name: 'Channel', dataSource: '', keys: [], fields: [], members: []});
    expect(bare.keys).toEqual(['code']);
    expect(bare.fields.map(f => `${f.name}:${f.type}`)).toEqual([
      'code:String', 'label:String', 'sort_order:Integer', 'definition:String',
      'iri:String'
    ]);
    const titled = withVocabularyBindings({
      name: 'Channel',
      dataSource: '',
      keys: [],
      fields: [{name: 'title', type: 'String'}],
      members: [],
    });
    expect(titled.keys).toEqual(['code']);
    expect(titled.fields.map(f => f.name)).toEqual(['code', 'title']);
  });

  test('the view is generated only for a source-less or vocab_ source', () => {
    const e = orderStatus();
    expect(generatesVocabularyView(e)).toBe(true);
    expect(generatesVocabularyView({...e, dataSource: 'unbound:x'})).toBe(true);
    expect(generatesVocabularyView({...e, dataSource: 'q.s.vocab_order_status'}))
        .toBe(true);
    expect(generatesVocabularyView({...e, dataSource: 'q.s.status_lookup'}))
        .toBe(false);
    expect(generatesVocabularyView({...e, members: undefined})).toBe(false);
    const other = {...e, dataSource: 'q.s.status_lookup'};
    expect(withVocabularyBindings(other)).toBe(other);
  });
});

describe('BigQuery lowering', () => {
  const gen = generatePropertyGraph(model(), GEN_OPTS);

  test('one vocab_<entity> view holds the members', () => {
    expect(gen.views?.find(v => v.kind === 'vocabulary')?.ddl).toBe(VOCAB_VIEW);
  });

  test('the node table reads the view, fields bound to its columns', () => {
    expect(flat(gen.ddl))
        .toContain(
            '`p.d.vocab_order_status` AS OrderStatus KEY(code) ' +
            'OPTIONS(description="Where an order is in its lifecycle.") ' +
            'PROPERTIES( code AS statusCode, label, sort_order AS sortOrder )');
  });

  test('an edge into the vocabulary matches the code case-insensitively', () => {
    expect(gen.views?.find(v => v.name === 'edge_has_status')?.ddl)
        .toBe(EDGE_VIEW);
    expect(flat(gen.ddl))
        .toContain(
            '`p.d.edge_has_status` AS hasStatus ' +
            'KEY(source_order_id, target_code) ' +
            'SOURCE KEY(source_order_id) REFERENCES `Order`(order_id) ' +
            'DESTINATION KEY(target_code) REFERENCES OrderStatus(code)');
  });

  test('views are listed in dependency order with their references', () => {
    expect(gen.views?.map(v => [v.kind, v.name, v.ref])).toEqual([
      ['vocabulary', 'vocab_order_status', 'p.d.vocab_order_status'],
      ['edge', 'edge_has_status', 'p.d.edge_has_status'],
    ]);
    expect(gen.warnings).toEqual([]);
  });

  test('a vocabulary bound to its own table keeps it; members document it',
       () => {
         const m = model();
         m.entities[1] = {
           ...orderStatus(),
           dataSource: 'p.d.status_lookup',
           fields: [
             {name: 'statusCode', type: 'String', expression: 'status_cd'},
             {name: 'label', type: 'String', expression: 'status_name'},
           ],
         };
         const out = generatePropertyGraph(m, GEN_OPTS);
         expect(out.views?.map(v => v.name)).toEqual(['edge_has_status']);
         expect(out.ddl).toContain('`p.d.status_lookup` AS OrderStatus');
         expect(out.views![0].ddl)
             .toContain('JOIN `p.d.status_lookup` AS v\n' +
                        '  ON LOWER(s.status_key) = LOWER(v.status_cd)');
       });

  test('a non-text foreign key is cast to STRING before matching', () => {
    const m = model();
    m.entities[0].fields[1].type = 'Integer';
    const out = generatePropertyGraph(m, GEN_OPTS);
    expect(out.views?.find(v => v.name === 'edge_has_status')?.ddl)
        .toContain('ON LOWER(CAST(s.status_key AS STRING)) = LOWER(v.code)');
  });

  test('a code field declared non-String is warned (the column is text)', () => {
    const m = model();
    m.entities[1].fields[0].type = 'Integer';
    const out = generatePropertyGraph(m, GEN_OPTS);
    expect(out.warnings.some(
               w => /field 'statusCode' reads the generated view's code column, which is STRING, but is declared Integer/
                        .test(w)))
        .toBe(true);
  });

  test('an empty vocabulary yields a typed empty view and a warning', () => {
    const m = model();
    m.entities[1].members = [];
    const out = generatePropertyGraph(m, GEN_OPTS);
    expect(out.views?.[0].ddl)
        .toContain(
            'SELECT * FROM UNNEST(ARRAY<STRUCT<code STRING, label STRING, ' +
            'sort_order INT64, definition STRING, iri STRING>>[])');
    expect(out.warnings).toContain(
        `entity 'OrderStatus': vocabulary with no members; its view ` +
        `'vocab_order_status' is empty`);
  });

  test('a model without a vocabulary is unchanged and has no views', () => {
    const m = model();
    m.entities[1] = {
      ...orderStatus(),
      members: undefined,
      dataSource: 'p.d.order_status',
      fields: [{name: 'statusCode', type: 'String', expression: 'code'}],
    };
    const out = generatePropertyGraph(m, GEN_OPTS);
    expect(out.views).toBeUndefined();
    expect(out.ddl).not.toContain('edge_has_status');
  });

  test('lowering does not mutate the input model', () => {
    const m = model();
    const before = JSON.stringify(m);
    lowerVocabularies(m, GEN_OPTS, []);
    expect(JSON.stringify(m)).toBe(before);
  });
});

describe('deploy', () => {
  const CTX = new ApiContext('test-project', 'us', 'test-token');
  const loaded = () => {
    const r = loadSemanticModels(
        [{name: 'orders', text: serializeModel(model()).yaml}],
        {defaultProject: 'p'});
    if (r.error) throw new Error(r.error);
    return r.models;
  };
  const mockDataset = () =>
      spyOn(bq.BigQueryClient.prototype, 'getDataset')
          .mockImplementation(
              async () => ({status: 200, result: {location: 'US'}} as any));

  test('validate-only lists the views ahead of the graph', async () => {
    const res = await deployBigQuery(loaded(), CTX, {validateOnly: true});
    expect(res.success).toBe(true);
    const ddl = res.ddl.join('\n');
    const at = (s: string) => ddl.indexOf(s);
    expect(at('VIEW `p.d.vocab_order_status`')).toBeGreaterThan(-1);
    expect(at('VIEW `p.d.vocab_order_status`'))
        .toBeLessThan(at('VIEW `p.d.edge_has_status`'));
    expect(at('VIEW `p.d.edge_has_status`'))
        .toBeLessThan(at('CREATE OR REPLACE PROPERTY GRAPH'));
  });

  test('push creates the views, in order, before the graph', async () => {
    const dsSpy = mockDataset();
    const querySpy =
        spyOn(bq.BigQueryClient.prototype, 'query')
            .mockImplementation(
                async () => ({status: 200, result: {jobComplete: true}}));
    try {
      const res = await deployBigQuery(loaded(), CTX, {});
      expect(res.success).toBe(true);
      const sqls = querySpy.mock.calls.map(c => String(c[1]));
      expect(sqls.length).toBe(3);
      expect(sqls[0]).toStartWith('CREATE OR REPLACE VIEW `p.d.vocab_order_status`');
      expect(sqls[1]).toStartWith('CREATE OR REPLACE VIEW `p.d.edge_has_status`');
      expect(sqls[2]).toContain('CREATE OR REPLACE PROPERTY GRAPH `p.d.g`');
    } finally {
      dsSpy.mockRestore();
      querySpy.mockRestore();
    }
  });

  test('a failing view stops the push before the graph, naming the view',
       async () => {
         const dsSpy = mockDataset();
         const querySpy = spyOn(bq.BigQueryClient.prototype, 'query')
                              .mockImplementation(
                                  async () => ({status: 400, message: 'boom'}));
         try {
           const res = await deployBigQuery(loaded(), CTX, {});
           expect(res.success).toBe(false);
           expect(res.details).toContain(`view 'p.d.vocab_order_status'`);
           expect(res.details).toContain('boom');
           expect(querySpy).toHaveBeenCalledTimes(1);
         } finally {
           dsSpy.mockRestore();
           querySpy.mockRestore();
         }
       });
});

