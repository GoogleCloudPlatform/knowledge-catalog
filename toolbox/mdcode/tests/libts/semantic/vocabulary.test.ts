describe('Knowledge Catalog push / pull', () => {
  const entryOf = (entries: any[], name: string) =>
      entries.find(e => e.entrySource?.displayName === name);

  test('push lists the members on the entity description', () => {
    const {entries} = generateCatalogResources(model(), KC_OPTS);
    expect(entryOf(entries, 'OrderStatus').entrySource.description)
        .toBe(
            'Where an order is in its lifecycle.\n\n' +
            'Members: "OPEN" — "Open"; "SHIPPED" — "Shipped"; ' +
            `"ON_HOLD" — "Customer's hold"; "VOID".`);
    expect(entryOf(entries, 'Order').entrySource.description ?? '')
        .not.toContain('Members:');
  });

  test('pull restores codes and labels; push is a fixed point', () => {
    const pushed = generateCatalogResources(model(), KC_OPTS);
    const {models, warnings} =
        modelsFromCatalogResources(pushed.entries, pushed.entryLinks);
    const status = models[0].entities.find(e => e.name === 'OrderStatus')!;
    expect(status.description).toBe('Where an order is in its lifecycle.');
    expect(status.members).toEqual([
      {code: 'OPEN', label: 'Open'},
      {code: 'SHIPPED', label: 'Shipped'},
      {code: 'ON_HOLD', label: `Customer's hold`},
      {code: 'VOID'},
    ]);
    expect(warnings.filter(w => w.includes('OrderStatus'))).toEqual([]);
    const again = generateCatalogResources(models[0], KC_OPTS);
    expect(entryOf(again.entries, 'OrderStatus').entrySource.description)
        .toBe(entryOf(pushed.entries, 'OrderStatus').entrySource.description);
  });
});

describe('members trailer codec', () => {
  test('forms', () => {
    expect(membersTrailer({members: []})).toBe('Members: none.');
    expect(membersTrailer({})).toBeUndefined();
    expect(membersTrailer({members: [{code: 'A', label: 'Alpha'}, {code: 'B'}]}))
        .toBe('Members: "A" — "Alpha"; "B".');
  });

  test('any character round-trips', () => {
    const members = [
      {code: 'a; b', label: 'x — y'},
      {code: 'q"uote', label: 'dot.'},
      {code: 'z'},
    ];
    const text = `Text.\n\n${membersTrailer({members})}`;
    expect(splitMembersTrailer(text)).toEqual({rest: 'Text.', members});
    expect(splitMembersTrailer(membersTrailer({members: []})))
        .toEqual({rest: undefined, members: []});
  });

  test('text without a well-formed trailer is left alone', () => {
    expect(splitMembersTrailer('Plain.')).toEqual({rest: 'Plain.'});
    expect(splitMembersTrailer('Plain.\n\nMembers: Open, Closed.'))
        .toEqual({rest: 'Plain.\n\nMembers: Open, Closed.'});
    expect(splitMembersTrailer(undefined)).toEqual({rest: undefined});
  });
});

