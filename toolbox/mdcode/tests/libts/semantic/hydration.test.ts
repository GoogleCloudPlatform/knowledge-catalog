describe('node views: golden DDL', () => {
  const lowered = () => {
    const warnings: string[] = [];
    const out = lowerNodeViews(model(), TARGET, warnings);
    return {...out, warnings};
  };
  const ddlOf = (name: string) =>
      lowered().views.find(v => v.name === name)!.ddl;

  test('views are ordered by dependency and planned one line each', () => {
    const {views, plan, warnings} = lowered();
    expect(warnings).toEqual([]);
    expect(views.map(v => [v.kind, v.ref, v.element])).toEqual([
      ['node', 'p.sem.opportunity', 'Opportunity'],
      ['node', 'p.sem.partner', 'Partner'],
      ['node', 'p.sem.market_unit', 'MarketUnit'],
    ]);
    expect(plan).toEqual([
      'node view p.sem.opportunity (Opportunity): latest version per ' +
          'opportunity_id by created_at; wonAmount ÷100 before 2024-03-25; ' +
          'marketUnit resolved to MarketUnit by marketUnitCode or unitName',
      'node view p.sem.partner (Partner): derived from withPartner',
      'node view p.sem.market_unit (MarketUnit): pass-through',
    ]);
  });

  test('pass-through: the modeled fields only, named snake_case(field)', () => {
    expect(ddlOf('market_unit')).toBe([
      'CREATE OR REPLACE VIEW `p.sem.market_unit`',
      `OPTIONS (description = 'Entity MarketUnit. Key: market_unit_code. ` +
          `Source: crm.market_unit. ${FOOTER}') AS`,
      'SELECT',
      '  t.code AS market_unit_code,',
      '  t.unit_name',
      'FROM `p.crm.market_unit` AS t',
    ].join('\n'));
  });

  test('grain latest_by + normalize + resolve', () => {
    expect(ddlOf('opportunity')).toBe([
      'CREATE OR REPLACE VIEW `p.sem.opportunity`',
      `OPTIONS (description = 'A sales opportunity. Key: opportunity_id. ` +
          `Hydration: latest version per opportunity_id by created_at; ` +
          `wonAmount ÷100 before 2024-03-25; marketUnit resolved to ` +
          `MarketUnit by marketUnitCode or unitName. Source: ` +
          `crm.opportunity. ${FOOTER}') AS`,
      'SELECT',
      '  t.opportunity_id,',
      '  t.created_at,',
      `  IF(CAST(t.created_at AS DATE) < DATE '2024-03-25', t.won_amount / 100, t.won_amount) AS won_amount,`,
      '  COALESCE(r0._kcmd_code, t.market_unit) AS market_unit,',
      '  t.partner_id',
      'FROM `p.crm.opportunity` AS t',
      'LEFT JOIN (',
      '  SELECT _kcmd_match, IF(COUNT(DISTINCT _kcmd_code) = 1, ANY_VALUE(_kcmd_code), NULL) AS _kcmd_code',
      '  FROM (',
      '    SELECT *, MIN(_kcmd_rank) OVER (PARTITION BY _kcmd_match) AS _kcmd_best',
      '    FROM (',
      '      SELECT LOWER(TRIM(d.code)) AS _kcmd_match, d.code AS _kcmd_code, 0 AS _kcmd_rank FROM `p.crm.market_unit` AS d',
      '      UNION ALL',
      '      SELECT LOWER(TRIM(d.unit_name)) AS _kcmd_match, d.code AS _kcmd_code, 1 AS _kcmd_rank FROM `p.crm.market_unit` AS d',
      '    )',
      '    WHERE _kcmd_match IS NOT NULL AND _kcmd_code IS NOT NULL',
      '  )',
      '  WHERE _kcmd_rank = _kcmd_best',
      '  GROUP BY _kcmd_match',
      ') AS r0',
      '  ON r0._kcmd_match = LOWER(TRIM(t.market_unit))',
      'QUALIFY ROW_NUMBER() OVER (PARTITION BY t.opportunity_id ORDER BY ' +
          't.created_at DESC, FARM_FINGERPRINT(TO_JSON_STRING(t))) = 1',
    ].join('\n'));
  });

  test('derive_from: the distinct foreign keys, read from the source view', () => {
    expect(ddlOf('partner')).toBe([
      'CREATE OR REPLACE VIEW `p.sem.partner`',
      `OPTIONS (description = 'Entity Partner. Key: partner_id. Hydration: ` +
          `derived from withPartner. Source: the distinct partnerId of ` +
          `Opportunity (relationship withPartner). ${FOOTER}') AS`,
      'SELECT DISTINCT s.partner_id AS partner_id',
      'FROM `p.sem.opportunity` AS s',
      'WHERE s.partner_id IS NOT NULL',
    ].join('\n'));
  });

  test('grain deterministic over a composite key', () => {
    const m: SemanticModel = {
      name: 'fin',
      entities: [{
        name: 'RateLine',
        dataSource: 'p.fin.rate_line',
        keys: ['contractId', 'lineNo'],
        fields: [
          {name: 'contractId', expression: 'contract_id'},
          {name: 'lineNo', expression: 'line_no'},
          {name: 'rate', expression: 'rate_amt'},
        ],
        hydration: {grain: {deterministic: true}},
      }],
      relationships: [],
      metrics: [],
    };
    const {views} = lowerNodeViews(m, TARGET, []);
    expect(views[0].ddl).toBe([
      'CREATE OR REPLACE VIEW `p.sem.rate_line`',
      `OPTIONS (description = 'Entity RateLine. Key: contract_id, line_no. ` +
          `Hydration: one row per contract_id, line_no (deterministic pick). ` +
          `Source: fin.rate_line. ${FOOTER}') AS`,
      'SELECT',
      '  t.contract_id,',
      '  t.line_no,',
      '  t.rate_amt AS rate',
      'FROM `p.fin.rate_line` AS t',
      'QUALIFY ROW_NUMBER() OVER (PARTITION BY t.contract_id, t.line_no ' +
          'ORDER BY FARM_FINGERPRINT(TO_JSON_STRING(t))) = 1',
    ].join('\n'));
  });

  test('normalize casts the column to the bound type, whatever its declared type', () => {
    const m = model();
    const opp = m.entities[2];
    opp.fields.push({name: 'closedOn', type: 'Date', expression: 'closed_on'});
    opp.hydration = {
      normalize: [{field: 'wonAmount', after: '2024-03-25', multiplyBy: 100, on: 'closed_on'}],
    };
    const {views} = lowerNodeViews(m, TARGET, []);
    expect(views.find(v => v.name === 'opportunity')!.ddl).toContain(
        `IF(CAST(t.closed_on AS DATE) >= DATE '2024-03-25', t.won_amount * 100, t.won_amount) AS won_amount`);
  });

  test('a DateTime field stored as a TIMESTAMP still compares (no DATETIME literal)', () => {
    const m = model();
    const opp = m.entities[2];
    opp.fields.push({name: 'loggedAt', type: 'DateTime', expression: 'logged_at'});
    opp.hydration = {
      normalize: [{field: 'wonAmount', before: '2024-03-25', divideBy: 100, on: 'logged_at'}],
    };
    const ddl = lowerNodeViews(m, TARGET, []).views.find(v => v.name === 'opportunity')!.ddl;
    expect(ddl).toContain(
        `IF(CAST(t.logged_at AS DATE) < DATE '2024-03-25', t.won_amount / 100, t.won_amount) AS won_amount`);
    expect(ddl).not.toContain('DATETIME');
  });

  test('a bound with a time part compares as TIMESTAMP', () => {
    const m = model();
    m.entities[2].hydration = {
      normalize: [{field: 'wonAmount', before: '2024-03-25T12:00:00Z', divideBy: 100, on: 'created_at'}],
    };
    expect(lowerNodeViews(m, TARGET, []).views.find(v => v.name === 'opportunity')!.ddl).toContain(
        `IF(CAST(t.created_at AS TIMESTAMP) < TIMESTAMP '2024-03-25T12:00:00Z', t.won_amount / 100, t.won_amount)`);
  });

  test('resolve against a vocabulary reads its members inline', () => {
    const m = model();
    m.entities.push({
      name: 'Stage',
      dataSource: '',
      keys: ['code'],
      fields: [{name: 'code'}, {name: 'label'}],
      members: [{code: 'won', label: 'Closed Won'}, {code: 'lost', label: 'Closed Lost'}],
    });
    m.entities[2].fields.push({name: 'stage', type: 'String', expression: 'stage'});
    m.entities[2].hydration!.resolve!.push({field: 'stage', match: ['code', 'label']});
    m.relationships.push({
      name: 'atStage',
      source: {entity: 'Opportunity', columns: ['stage']},
      destination: {entity: 'Stage', columns: ['code']},
    });
    expect(checkHydration(m).errors).toEqual([]);
    const {views} = lowerNodeViews(m, TARGET, []);
    const ddl = views.find(v => v.name === 'opportunity')!.ddl;
    expect(ddl).toContain(`'Closed Won'`);
    expect(ddl).toContain('UNNEST([STRUCT(');
    expect(ddl).toContain('COALESCE(r1._kcmd_code, t.stage) AS stage');
    // A vocabulary keeps its own generated view; it gets no node view.
    expect(views.map(v => v.name)).not.toContain('stage');
  });

  test('the graph reads the node views', () => {
    const {model: lowered} = lowerNodeViews(model(), TARGET, []);
    const {ddl} = generatePropertyGraph(lowered, GRAPH);
    expect(ddl).toContain('`p.sem.opportunity` AS Opportunity');
    expect(ddl).toContain('`p.sem.partner` AS Partner');
    expect(ddl).toContain('`p.sem.market_unit` AS MarketUnit');
    expect(ddl).not.toContain('p.crm.opportunity');
    // Fields read their view column by name.
    expect(ddl).toContain('won_amount AS wonAmount');
  });

  test('mode: direct binds the source; resolve moves to an edge view', () => {
    const m = model();
    const opp = m.entities[2];
    opp.mode = 'direct';
    opp.hydration = {resolve: [{field: 'marketUnit', match: ['marketUnitCode', 'unitName']}]};
    const warnings: string[] = [];
    const {model: lowered, views, plan} = lowerNodeViews(m, TARGET, warnings);
    expect(views.map(v => [v.kind, v.name])).toEqual([
      ['node', 'partner'],
      ['node', 'market_unit'],
      ['edge', 'edge_in_market_unit'],
    ]);
    expect(plan[2]).toBe(
        'edge view p.sem.edge_in_market_unit (inMarketUnit): marketUnit ' +
        'resolved to MarketUnit by marketUnitCode or unitName');
    const edge = views[2].ddl;
    expect(edge).toContain(
        'SELECT s.opportunity_id AS source_opportunity_id, r._kcmd_code AS target_market_unit_code');
    expect(edge).toContain('FROM `p.crm.opportunity` AS s');
    expect(edge).toContain('  ON r._kcmd_match = LOWER(TRIM(s.market_unit))');
    expect(lowered.entities.find(e => e.name === 'Opportunity')!.dataSource)
        .toBe('p.crm.opportunity');
    // Partner's view reads the direct source table instead of a view.
    expect(views[0].ddl).toContain('FROM `p.crm.opportunity` AS s');
    const rel = lowered.relationships.find(r => r.name === 'inMarketUnit')!;
    expect(rel.association?.dataSource).toBe('p.sem.edge_in_market_unit');
  });

  test('a view that would replace a bound table falls back to direct', () => {
    const m = model();
    m.entities[1].dataSource = 'p.sem.market_unit';
    const warnings: string[] = [];
    const {views} = lowerNodeViews(m, TARGET, warnings);
    expect(views.map(v => v.name)).not.toContain('market_unit');
    expect(warnings).toEqual([expect.stringContaining(
        `entity 'MarketUnit': its node view 'p.sem.market_unit' would replace its own source table`)]);
  });

  test('a derived entity binds its key to the view column', () => {
    expect(withHydrationBindings(partner()).fields)
        .toEqual([{name: 'partnerId', type: 'String', expression: 'partner_id'}]);
    expect(withHydrationBindings(marketUnit())).toEqual(marketUnit());
  });
});

describe('deploy', () => {
  const loaded = () => [{document: 'doc.yaml', model: model()} as any];

  test('dry run lists node views first and plans them', async () => {
    const querySpy = spyOn(bq.BigQueryClient.prototype, 'query');
    try {
      const res = await deployBigQuery(loaded(), CTX, {validateOnly: true});
      expect(res.success).toBe(true);
      expect(querySpy).not.toHaveBeenCalled();
      const block = res.ddl[0];
      const at = (s: string) => block.indexOf(s);
      expect(at('VIEW `p.sem.opportunity`')).toBeGreaterThan(-1);
      expect(at('VIEW `p.sem.opportunity`')).toBeLessThan(at('VIEW `p.sem.partner`'));
      expect(at('VIEW `p.sem.market_unit`'))
          .toBeLessThan(at('CREATE OR REPLACE PROPERTY GRAPH'));
      expect(res.nodeViews).toEqual([
        expect.stringMatching(/^\[sales -> g\] node view p\.sem\.opportunity/),
        expect.stringMatching(/^\[sales -> g\] node view p\.sem\.partner/),
        expect.stringMatching(/^\[sales -> g\] node view p\.sem\.market_unit/),
      ]);
    } finally {
      querySpy.mockRestore();
    }
  });

  test('nodeViews: false binds every source directly', async () => {
    const res = await deployBigQuery(
        loaded(), CTX, {validateOnly: true, nodeViews: false});
    expect(res.nodeViews).toEqual([]);
    expect(res.ddl[0]).not.toContain('VIEW `p.sem.opportunity`');
  });

  test('a failing node view names the entity and its hydration', async () => {
    const dsSpy = spyOn(bq.BigQueryClient.prototype, 'getDataset')
                      .mockImplementation(
                          async () => ({status: 200, result: {location: 'US'}} as any));
    const querySpy =
        spyOn(bq.BigQueryClient.prototype, 'query')
            .mockImplementation(async () => ({
                                  status: 400,
                                  message: 'Unrecognized name: created_at',
                                } as any));
    try {
      const res = await deployBigQuery(loaded(), CTX, {});
      expect(res.success).toBe(false);
      expect(res.details).toBe(
          `Failed to create node view 'p.sem.opportunity' for entity ` +
          `'Opportunity': Unrecognized name: created_at; check the entity's ` +
          `source, its field columns and its hydration columns ` +
          `(grain.latest_by, normalize.on)`);
      expect(querySpy).toHaveBeenCalledTimes(1);
    } finally {
      dsSpy.mockRestore();
      querySpy.mockRestore();
    }
  });
});

describe('availability', () => {
  test('a derived entity stays when its relationship\'s join field is unbound', () => {
    // Join columns are physical columns, not fields, so unbinding the field
    // that shares the column's name drops the field and nothing else: the
    // relationship stays, and the entity derived from it with it.
    const m = model();
    const opp = m.entities[2];
    opp.fields = opp.fields.map(
        f => f.name === 'partnerId' ? {name: 'partnerId', type: 'String'} : f);
    const {model: pruned, report} = pruneUnavailable(m, 'bq');
    expect(pruned.entities.map(e => e.name)).toContain('Partner');
    expect(pruned.relationships.map(r => r.name)).toContain('withPartner');
    expect(report.droppedEntities).toEqual([]);
    expect(report.droppedRelationships).toEqual([]);
    expect(report.unboundFields).toContain('Opportunity.partnerId');
  });

  test('a derived entity\'s key counts as bound', () => {
    const {model: pruned, report} = pruneUnavailable(model(), 'bq');
    expect(report.droppedEntities).toEqual([]);
    expect(pruned.entities.find(e => e.name === 'Partner')!.fields)
        .toEqual([{name: 'partnerId', type: 'String', expression: 'partner_id'}]);
  });
});

describe('Knowledge Catalog push / pull', () => {
  const entryOf = (entries: any[], name: string) =>
      entries.find(e => e.entrySource?.displayName === name);

  test('push records the hydration last on the entity description', () => {
    const {entries} = generateCatalogResources(model(), KC_OPTS);
    expect(entryOf(entries, 'Opportunity').entrySource.description).toBe(
        'A sales opportunity.\n\nHydration: latest version per opportunity_id ' +
        'by created_at; wonAmount ÷100 before 2024-03-25; marketUnit resolved ' +
        'to MarketUnit by marketUnitCode or unitName.');
    expect(entryOf(entries, 'Partner').entrySource.description)
        .toBe('Hydration: derived from withPartner.');
    // A pass-through entity carries no trailer.
    expect(entryOf(entries, 'MarketUnit').entrySource.description).toBeUndefined();
  });

  test('pull restores hydration and mode', () => {
    const m = model();
    m.entities[1].mode = 'direct';
    const pushed = generateCatalogResources(m, KC_OPTS);
    const {models, warnings} =
        modelsFromCatalogResources(pushed.entries, pushed.entryLinks);
    const byName = new Map(models[0].entities.map(e => [e.name, e]));
    expect(byName.get('Opportunity')!.description).toBe('A sales opportunity.');
    expect(byName.get('Opportunity')!.hydration).toEqual(m.entities[2].hydration);
    expect(byName.get('Partner')!.hydration).toEqual(m.entities[0].hydration);
    expect(byName.get('MarketUnit')!.mode).toBe('direct');
    expect(warnings.some(w => /entity 'Partner': no backing data source/.test(w)))
        .toBe(false);
  });

  test('pull writes hydration back into the document', () => {
    const doc = modelDocument(model());
    const opp = doc.semantic_model[0].entities.find((e: any) => e.name === 'Opportunity');
    expect(opp.hydration).toEqual({
      grain: {latest_by: 'created_at'},
      normalize: [{field: 'wonAmount', before: '2024-03-25', divide_by: 100}],
      resolve: [{field: 'marketUnit', match: ['marketUnitCode', 'unitName']}],
    });
    const p = doc.semantic_model[0].entities.find((e: any) => e.name === 'Partner');
    expect(p.source).toBeUndefined();
    expect(p.hydration).toEqual({derive_from: {relationship: 'withPartner'}});
  });

  test('splitHydrationTrailer leaves other paragraphs alone', () => {
    expect(splitHydrationTrailer('Plain.\n\nHydration: something else.'))
        .toEqual({rest: 'Plain.\n\nHydration: something else.'});
    expect(splitHydrationTrailer('Hydration: bound directly (no node view).'))
        .toEqual({rest: undefined, mode: 'direct'});
  });

  test('clauses carry an explicit normalize column', () => {
    expect(hydrationClauses({
      keys: ['id'],
      hydration: {normalize: [{field: 'a', after: '2024-01-01', multiplyBy: 0.5, on: 'd'}]},
    })).toEqual(['a ×0.5 from 2024-01-01 by d']);
  });
});
