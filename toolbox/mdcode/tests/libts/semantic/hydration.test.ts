describe('the hydration block is closed', () => {
  test('the running example rules are well formed', () => {
    expect(hydrationDocErrors({
      grain: {latest_by: 'created_at'},
      normalize: [{field: 'wonAmount', before: '2024-03-25', divide_by: 100}],
      resolve: [{field: 'marketUnit', match: ['marketUnitCode', 'unitName']}],
    })).toEqual([]);
    expect(hydrationDocErrors({derive_from: {relationship: 'withPartner'}}))
        .toEqual([]);
  });

  test('an unknown rule (e.g. SQL) is rejected by name', () => {
    const errors = hydrationDocErrors({sql: 'SELECT 1'});
    expect(errors.length).toBe(1);
    expect(errors[0]).toContain(`'hydration' sets 'sql', which is not a hydration rule`);
  });

  test('each rule shape is checked', () => {
    expect(hydrationDocErrors({grain: {latest_by: 'a', deterministic: true}})
               .some(e => /exactly one of latest_by/.test(e)))
        .toBe(true);
    expect(hydrationDocErrors({grain: {latest_by: 'MAX(a)'}})
               .some(e => /not an expression/.test(e)))
        .toBe(true);
    expect(hydrationDocErrors({normalize: [{field: 'x', divide_by: 100}]})
               .some(e => /exactly one of before or after/.test(e)))
        .toBe(true);
    expect(hydrationDocErrors({normalize: [{field: 'x', before: 'soon', divide_by: 0}]}))
        .toEqual(expect.arrayContaining([
          expect.stringContaining('before must be an ISO date'),
          expect.stringContaining('divide_by must be a number > 0'),
        ]));
    expect(hydrationDocErrors({resolve: [{field: 'x', match: []}]})
               .some(e => /match must be a non-empty list/.test(e)))
        .toBe(true);
    expect(hydrationDocErrors({
      derive_from: {relationship: 'r'},
      grain: {deterministic: true},
    }).some(e => /derive_from' stands alone/.test(e))).toBe(true);
  });
});

describe('loader', () => {
  const doc = (ds: any, version = '0.2.0.dev0/google') => ({
    version,
    semantic_model: [{
      name: 'm',
      datasets: [{
        name: 'Opportunity',
        source: 'bigquery:p.crm.opportunity',
        primary_key: ['id'],
        fields: [
          {name: 'id', expression: 'id'},
          {name: 'amount', expression: 'amount'},
        ],
        ...ds,
      }],
    }],
  });

  test('hydration and mode load onto the IR', () => {
    const {models, warnings} = fromDocument(doc({
      hydration: {
        grain: {latest_by: 'created_at'},
        normalize: [{field: 'amount', after: '2024-03-25', multiply_by: 100}],
      },
      mode: 'view',
    }));
    const e = models[0].entities[0];
    expect(e.hydration).toEqual({
      grain: {latestBy: 'created_at'},
      normalize: [{field: 'amount', after: '2024-03-25', multiplyBy: 100}],
    });
    expect(e.mode).toBe('view');
    expect(warnings).toEqual([]);
  });

  test('an unknown hydration rule or mode is a load error', () => {
    expect(() => fromDocument(doc({hydration: {filter: 'x > 1'}})))
        .toThrow(/not a hydration rule/);
    expect(() => fromDocument(doc({mode: 'materialized'})))
        .toThrow(/'mode' must be 'view' or 'direct'/);
  });

  test('the keys are native extensions: vanilla Ossie rejects them', () => {
    expect(() => fromDocument(doc({mode: 'direct'}, '0.2.0.dev0'))).toThrow();
  });

  test('a derived dataset needs no source', () => {
    const {models} = fromDocument({
      version: '0.2.0.dev0/google',
      semantic_model: [{
        name: 'm',
        datasets: [
          {
            name: 'Opportunity',
            source: 'bigquery:p.crm.opportunity',
            primary_key: ['id'],
            fields: [
              {name: 'id', expression: 'id'},
              {name: 'partnerId', expression: 'partner_id'},
            ],
          },
          {
            name: 'Partner',
            primary_key: ['partnerId'],
            fields: [{name: 'partnerId'}],
            hydration: {derive_from: {relationship: 'withPartner'}},
          },
        ],
        relationships: [{
          name: 'withPartner',
          from: 'Opportunity',
          to: 'Partner',
          from_columns: ['partnerId'],
          to_columns: ['partnerId'],
        }],
      }],
    });
    const p = models[0].entities.find(e => e.name === 'Partner')!;
    expect(p.dataSource).toBe('');
    expect(p.hydration).toEqual({deriveFrom: {relationship: 'withPartner'}});
  });

  test('a rule naming no field loads with a warning', () => {
    const {warnings} = fromDocument(doc({
      hydration: {normalize: [{field: 'nope', before: '2024-01-01', divide_by: 10, on: 'd'}]},
    }));
    expect(warnings.some(w => /hydration\.normalize names 'nope'/.test(w))).toBe(true);
  });
});

describe('profile merge', () => {
  const logical = () => ({
    version: '0.2.0.dev0/google',
    semantic_model: [{
      name: 'm',
      entities: [{
        name: 'Opportunity',
        primary_key: ['id'],
        fields: [{name: 'id'}, {name: 'amount'}],
        hydration: {grain: {deterministic: true}},
      }],
    }],
  });
  const profile = (entity: any) => ({
    version: '0.2.0.dev0/google',
    semantic_model: [{
      name: 'm',
      entities: [{name: 'Opportunity', source: 'bigquery:p.crm.opp', ...entity}],
    }],
  });
  const entityOf = (doc: any) => doc.semantic_model[0].entities[0];

  test('a profile sets hydration and mode, replacing the model\'s whole', () => {
    const r = mergeProfile(logical(), profile({
      hydration: {grain: {latest_by: 'created_at'}},
      mode: 'view',
    }), 'bq');
    expect(r.error).toBeUndefined();
    expect(entityOf(r.doc).hydration).toEqual({grain: {latest_by: 'created_at'}});
    expect(entityOf(r.doc).mode).toBe('view');
  });

  test('null withdraws the model\'s hydration', () => {
    const r = mergeProfile(logical(), profile({hydration: null}), 'bq');
    expect(r.error).toBeUndefined();
    expect(entityOf(r.doc).hydration).toBeUndefined();
  });

  test('an unknown rule is rejected naming the profile and entity', () => {
    const r = mergeProfile(
        logical(), profile({hydration: {sql: 'SELECT DISTINCT *'}}), 'bq');
    expect(r.error).toContain(`profile 'bq': entity 'Opportunity' 'hydration' sets 'sql'`);
  });

  test('a bad mode is rejected', () => {
    const r = mergeProfile(logical(), profile({mode: 'table'}), 'bq');
    expect(r.error).toContain(`'mode' must be 'view' or 'direct'`);
  });

  test('other entity keys stay logical declarations', () => {
    const r = mergeProfile(logical(), profile({description: 'x'}), 'bq');
    expect(r.error).toContain(
        `entity 'Opportunity' sets 'description', which a profile may not set`);
  });
});

