// Tests for `kcmd profile` (src/tool/commands.ts, profile()) and the
// `kcmd push --strict-profile` gate (profileGate()), both proposed. The
// command runs in a temp semantic-model scope with a pinned context and the
// BigQuery / Knowledge Catalog clients stubbed, so nothing leaves the process:
// every query is answered from fixtures/data_profile/shop.results.yaml, the
// rows the library goldens (profile_bigquery.test.ts) are built from.

import {afterEach, beforeEach, describe, expect, mock, spyOn, test} from 'bun:test';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';

import * as yaml from 'yaml';

import * as bq from '../../../src/libts/gcp/bigquery';
import {ApiContext} from '../../../src/libts/gcp/context';
import {CatalogClient} from '../../../src/libts/gcp/dataplex';
import {loadSemanticModels} from '../../../src/libts/semantic/loader';
import {planBigQueryProfile, QueryRow} from '../../../src/libts/semantic/profile_bigquery';
import {profile, profileGate} from '../../../src/tool/commands';

const FIXTURES = path.join(__dirname, 'fixtures', 'data_profile');
const SHOP = fs.readFileSync(path.join(FIXTURES, 'shop.yaml'), 'utf8');
const ROWS =
    yaml.parse(fs.readFileSync(path.join(FIXTURES, 'shop.results.yaml'), 'utf8')) as Record<string, QueryRow>;
const CTX = new ApiContext('test-project', 'us', 'test-token');

let dir = '';
let cwd = '';
let logs: string[] = [];

// The scope `kcmd profile` reads: catalog.yaml and one model document.
function writeScope(text = SHOP): void {
  fs.writeFileSync(path.join(dir, 'catalog.yaml'), 'scope: semantic-model.test-project.us.shop_eg\n');
  const eg = path.join(dir, 'catalog', 'EntryGroups', 'shop_eg');
  fs.mkdirSync(eg, {recursive: true});
  fs.writeFileSync(path.join(eg, 'shop.yaml'), text);
}

// The model as the command loads it, so its plan's SQL is the command's.
function loaded(text = SHOP) {
  return loadSemanticModels([{name: 'shop', text}], {defaultProject: 'test-project', bindingOptional: true})
      .models;
}

function ok(row: QueryRow) {
  return {
    status: 200,
    result: {
      jobComplete: true,
      schema: {fields: Object.keys(row).map(name => ({name}))},
      rows: [{f: Object.values(row).map(v => ({v}))}],
    },
  };
}

// Answers each query with the fixture row filed under the first statement it
// settles; a query with no row fails, as BigQuery would on a bad column.
function stubQueries(rows: Record<string, QueryRow> = ROWS) {
  const plan = planBigQueryProfile(loaded()[0].model);
  const bySql = new Map<string, QueryRow>();
  for (const [id, row] of Object.entries(rows)) {
    bySql.set(plan.checks.find(c => c.id === id)!.sql, row);
  }
  return spyOn(bq.BigQueryClient.prototype, 'query').mockImplementation(async (_p: string, sql: string) => {
    const row = bySql.get(sql);
    return row ? ok(row) : {status: 400, message: JSON.stringify({error: {message: 'Unrecognized name: x'}})};
  });
}

const out = (file: string) => path.join(dir, 'profiling', file);

beforeEach(() => {
  cwd = process.cwd();
  dir = fs.mkdtempSync(path.join(os.tmpdir(), 'kcmd-profile-'));
  process.chdir(dir);
  logs = [];
  spyOn(ApiContext, 'default').mockReturnValue(CTX);
  for (const level of ['log', 'warn', 'error'] as const) {
    spyOn(console, level).mockImplementation((...a: any[]) => {
      logs.push(a.join(' '));
    });
  }
});

afterEach(() => {
  process.chdir(cwd);
  if (dir) fs.rmSync(dir, {recursive: true, force: true});
  dir = '';
  mock.restore();
});


describe('kcmd profile', () => {
  test('writes the queries, runs each once with the labels, and reports every statement', async () => {
    writeScope();
    const query = stubQueries();
    expect(await profile({label: ['team:data', 'env:dev']})).toBe(0);

    expect(fs.readFileSync(out('profile.sql'), 'utf8'))
        .toStartWith('-- Generated by kcmd profile for model \'shop\' (profile \'default\').');
    const report = JSON.parse(fs.readFileSync(out('profile.json'), 'utf8'));
    expect(report.profile).toBe('default');
    expect(report.models.map((m: any) => [m.model, m.summary]))
        .toEqual([['shop', {verified: 14, unverified: 3, contradicted: 6}]]);
    // The same statuses and evidence as the library golden, through the CLI.
    const golden = JSON.parse(fs.readFileSync(path.join(FIXTURES, 'shop.profile.golden.json'), 'utf8'));
    expect(report.models[0].statements.map(({sql: _sql, ...rest}: any) => rest)).toEqual(golden);
    expect(fs.readFileSync(out('profile.md'), 'utf8')).toContain('| contradicted | orphans | Order.placedBy |');

    expect(query).toHaveBeenCalledTimes(Object.keys(ROWS).length);
    for (const call of query.mock.calls) {
      expect([call[0], call[3], call[5]]).toEqual(['test-project', false, {team: 'data', env: 'dev'}]);
    }
    expect(logs).toContain('[shop] 23 statement(s) in 15 query(ies); 4 claim(s) not profiled (listed in profile.sql).');
    expect(logs.some(l => l.startsWith('STATUS'))).toBe(true);
  });

  test('--strict fails the run when the data contradicts a statement', async () => {
    writeScope();
    stubQueries();
    expect(await profile({strict: true, out: 'reports'})).toBe(1);
    expect(fs.existsSync(path.join(dir, 'reports', 'profile.json'))).toBe(true);
    expect(logs).toContain('Error: --strict: the data contradicts 6 statement(s).');
  });

  test('--project and --location go to every job', async () => {
    writeScope();
    const query = stubQueries();
    await profile({project: 'jobs-proj', location: 'EU'});
    expect(query.mock.calls.every(c => c[0] === 'jobs-proj' && c[2] === 'EU')).toBe(true);
  });

  test('a query that cannot run fails the command; its statements stay unverified', async () => {
    writeScope();
    const {Customer_segment_in: _dropped, ...rest} = ROWS;
    stubQueries(rest);
    expect(await profile({})).toBe(1);
    const report = JSON.parse(fs.readFileSync(out('profile.json'), 'utf8'));
    expect(report.models[0].statements.find((s: any) => s.id === 'Customer_segment_in'))
        .toMatchObject({status: 'unverified', error: 'Unrecognized name: x'});
  });

  test('--sql-only (or no credentials) writes the queries and runs nothing', async () => {
    writeScope();
    const query = stubQueries();
    expect(await profile({sqlOnly: true})).toBe(0);
    expect(fs.existsSync(out('profile.sql'))).toBe(true);
    expect(fs.existsSync(out('profile.json'))).toBe(false);

    query.mockClear();
    spyOn(ApiContext, 'default').mockReturnValue(new ApiContext('test-project', 'us', ''));
    expect(await profile({})).toBe(0);
    expect(logs).toContain('Warning: no credentials; writing the queries only (as --sql-only).');
    expect(query).not.toHaveBeenCalled();
  });

  test('--publish --dry-run prints the Knowledge Catalog requests and sends none', async () => {
    writeScope();
    stubQueries();
    const create = spyOn(CatalogClient.prototype, 'createAspectType');
    const update = spyOn(CatalogClient.prototype, 'updateEntry');
    expect(await profile({publish: true, dryRun: true})).toBe(0);
    expect(create).not.toHaveBeenCalled();
    expect(update).not.toHaveBeenCalled();
    expect(logs.filter(l => l.startsWith('PATCH projects/test-project/locations/us/entryGroups/shop_eg/entries/')))
        .toHaveLength(4);
    expect(logs).toContain('Dry run: 4 entry update(s) for \'shop\' printed, none sent.');
  });

  test('usage errors stop before anything is written or run', async () => {
    writeScope();
    const query = stubQueries();
    const cases: Array<[Parameters<typeof profile>[0], string]> = [
      [{target: 'spanner'}, 'Error: --target must be \'bigquery\'; got \'spanner\'.'],
      [{publish: true, sqlOnly: true}, 'Error: --publish and --sql-only cannot be combined.'],
      [{examples: '-1'}, 'Error: --examples must be a whole number >= 0; got \'-1\'.'],
      [{shiftFactor: 'x'}, 'Error: --shift-factor must be a number > 1; got \'x\'.'],
      [{label: 'Team:data'}, 'Error: --label must be key:value with lowercase letters, digits, \'_\' or \'-\'; got \'Team:data\'.'],
      [{profile: 'nope'}, 'Error: unknown binding profile \'nope\' for model \'shop\'; no profiles are defined for this model.'],
    ];
    for (const [options, message] of cases) {
      expect(await profile(options)).toBe(1);
      expect(logs).toContain(message);
    }
    expect(fs.existsSync(path.join(dir, 'profiling'))).toBe(false);
    expect(query).not.toHaveBeenCalled();
  });

  test('--dry-run without --publish is a warning, not an error', async () => {
    writeScope();
    stubQueries();
    expect(await profile({dryRun: true, sqlOnly: true})).toBe(0);
    expect(logs).toContain('Warning: --dry-run only applies to --publish; ignoring it.');
  });
});


describe('push --strict-profile gate', () => {
  test('contradicted statements stop the deploy and are listed', async () => {
    stubQueries();
    expect(await profileGate(loaded(), CTX, 'default')).toBe(false);
    expect(logs.some(l => l.startsWith('Error: [shop] the data bound by profile \'default\' contradicts 6 statement(s); not deploying')))
        .toBe(true);
    expect(logs.some(l => l.includes('contradicted  orphans'))).toBe(true);
  });

  test('unverified statements, failed queries included, never block', async () => {
    // Keep only the queries whose statements all verify; every other query
    // fails, so its statements are unverified.
    const passing = ['Customer_primary_key', 'Order_primary_key', 'Invoice_primary_key'];
    stubQueries(Object.fromEntries(passing.map(id => [id, ROWS[id]])));
    expect(await profileGate(loaded(), CTX, 'default')).toBe(true);
    expect(logs).toContain('Profile gate: [shop] 3 verified, 20 unverified, none contradicted.');
  });
});
